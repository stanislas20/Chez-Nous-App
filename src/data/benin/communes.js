// Bénin's 77 communes, from the official roll rather than from memory.
//
// The app shipped 61 names. Seventeen real communes could not be selected at
// all — a seller in Boukoumbé or Ségbana had nowhere to say where they were —
// one entry ("Ikpinlé") is not a commune, and one carried a typo.
//
// ── Where each field comes from ────────────────────────────────────────
//
// IDENTITY AND GEOMETRY are from the OCHA/HDX Common Operational Dataset for
// Bénin (COD-AB v01, admin levels 0-2, reviewed 2026-01-26): the p-code, the
// commune -> department relationship and the centroid. That source is
// authoritative and machine-readable, which is why nothing here is typed by
// hand or inferred.
//
// DISPLAY NAMES are not. Every name column in COD-AB is unaccented despite
// declaring lang "fr" — "Aplahoue", "Ketou", "Seme-Kpodji" — so taking its
// strings would have degraded 21 names the app already had right, and broken
// the exact-string match against `city` on every listing already stored under
// the accented spelling. So `name` is the verified French spelling,
// corroborated against the Association Nationale des Communes du Bénin and
// the French Wikipedia list of communes, and `sourceName` keeps the COD-AB
// string so the two can always be reconciled.
//
// Three names disagree beyond accents, and the research went the other way
// each time:
//
//   BJ0203  COD-AB says "Kobli". ANCB uses "Cobly" 44 times and "Kobli"
//           never; Wikipedia has no "Kobli". Display is Cobly.
//   BJ1004  COD-AB says "Akpo-Misserete", which drops an r. The app was
//           already right: Akpro-Missérété.
//   BJ0307  COD-AB says "Tori-Bossito" and the APP was wrong
//           ("Torri-Bossito"). Display is Tori-Bossito; the typo lives on in
//           aliases because listings were stored under it.
//
// Two have two legitimate forms and the choice is cosmetic — Boukoumbé /
// Boukombé and Ségbana / Segbana, both attested. Both forms are in aliases,
// so the decision can be reversed by moving one string.
//
// ── Why aliases exist ──────────────────────────────────────────────────
//
// A listing stores `city` as a display string, and thousands already exist.
// Renaming a commune would orphan every one of them from its own filter. So
// nothing is ever rewritten: aliases carry every spelling a document might
// hold — the COD-AB form, the old app form, the variant — and resolveCommune
// maps any of them to one p-code. That is also what makes this extensible:
// when arrondissements and quartiers arrive they hang off `code`, not off a
// name that might change.

