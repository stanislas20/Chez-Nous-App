// Accent- and case-insensitive, because the same commune arrives spelled four
// ways: from a stored listing, from COD-AB, from a seller typing it, and from
// this file.
function fold(value) {
  return String(value ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
}

const index = new Map();
for (const commune of communes) {
  for (const key of [commune.name, commune.sourceName, ...commune.aliases]) {
    index.set(fold(key), commune);
  }
}

/** The commune a stored or typed name refers to, or null. */
export function resolveCommune(value) {
  return index.get(fold(value)) ?? null;
}

/** Display name for any known spelling; unknown values are returned as given. */
export function canonicalCityName(value) {
  return resolveCommune(value)?.name ?? value ?? null;
}

/** Selectable commune names, in the order the app has always shown them. */
export const communeNames = communes.map((commune) => commune.name);
