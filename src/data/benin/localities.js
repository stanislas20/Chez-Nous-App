// Bénin's arrondissements and their villages and quartiers de ville.
//
// Phase 1 stopped at the commune, which is where a property search stops
// being useful: "Abomey-Calavi" is Godomey and Calavi centre and Womey, an
// hour apart and half the price apart. This file is the two levels below it.
//
// ── Where it comes from ───────────────────────────────────────────────
//
// INStaD's CAHIERS DES VILLAGES ET QUARTIERS DE VILLE (RGPH-4, août 2016),
// one per department, twelve documents. That is the administrative roll
// itself, not a rendering of it: each table runs
//
//     DEP: LITTORAL / COM: COTONOU / ARROND: 1er Arrondissement / DANDJI …
//
// so the parent of every row is stated by the document, never inferred. The
// extraction reproduces each cahier's own stated totals: 546 arrondissements
// nationally, matching all twelve prose figures and the official count, and
// 77 communes, matching Phase 1 exactly.
//
// THE OTHER TWO SOURCES ARE CORROBORATION, NOT STRUCTURE. GeoNames (CC-BY
// 4.0) supplies accented spellings and the only coordinates here, accepted
// solely where one populated-place record of that name sits inside the
// commune's authoritative OCHA/HDX COD-AB boundary. geoBoundaries ADM3
// independently produces 546 arrondissements and agrees on 465 names, which
// is why the count is trustworthy — but its geometry disagrees with GeoNames
// too often to place anything (it puts KANDI I's own point in Kandi II), so
// no parent in this file rests on it.
//
// ── What the ids are, and are not ─────────────────────────────────────
//
// Bénin publishes no p-code below the commune: COD-AB stops at admin 2 and
// the cahiers carry no identifier column. So `id` is DERIVED — the Phase 1
// commune p-code, then position in the cahier — and must not be presented as
// official or shown to anybody. It is stable only because the 2016 documents
// are fixed and this file preserves their order; inserting a row renumbers
// every id after it, which is why check-benin-localities.js pins the counts
// rather than trusting them. The check validates this file's internal shape,
// NOT the PDFs — re-extracting them is a manual step.
//
// ── Why names are stored twice ────────────────────────────────────────
//
// The cahiers set every locality in capitals, which in French drops accents:
// GBEDJROMEDE. `name` is for reading, `sourceName` is the cahier's own
// string, and nothing is accented by guesswork — the 199 accented locality
// names are GeoNames spellings that matched fold-for-fold inside the right
// commune. The rest are merely title-cased, so Gbedjromede is missing its
// accents rather than wearing invented ones.

