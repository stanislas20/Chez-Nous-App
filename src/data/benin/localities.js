function fold(value) {
  return String(value ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
}

const deaccentUpper = (value) =>
  String(value).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase();

