// A marque with no catalogue entry still works — the picker falls back to
// free text on the publish form and to what listings contain when browsing.
export function modelsForBrand(brand) {
  return vehicleModels[brand] ?? [];
}

export function allVehicleModels() {
  return Object.values(vehicleModels).flat();
}
